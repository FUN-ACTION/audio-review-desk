"""Update lightweight playback metadata from the verified media manifest."""
import hashlib
import json
from pathlib import Path


def main():
    root = Path(__file__).resolve().parents[1]
    media = root / 'src/audio_review_desk/static/tour/media'
    record = json.loads((root/'docs/showcase-media.json').read_text(encoding='utf-8'))
    durations = {}
    for clip in record['clips']:
        kind, language = Path(clip['file']).stem.rsplit('-',1)
        if kind not in {'workflow','notes','range'} or language not in {'zh','en'}:
            raise ValueError('Unexpected recording name')
        data = (media/clip['file']).read_bytes()
        if hashlib.sha256(data).hexdigest() != clip['sha256']:
            raise ValueError(f"Update the media manifest first: {clip['file']}")
        durations.setdefault(kind,{})[language] = clip['seconds']
    target = root/'src/audio_review_desk/static/tour/media-info.js'
    target.write_text('// Generated by scripts/update_showcase_index.py\nexport const filmDurations = '
                      + json.dumps(durations,indent=2) + ';\n',encoding='utf-8')


if __name__ == '__main__':
    main()
